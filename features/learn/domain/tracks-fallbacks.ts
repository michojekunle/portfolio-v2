/** Returns a track-authentic fallback lesson for guests, new users, and AI outages. */
export function fallbackLessonForTrack(
  pack: Pick<LanguagePack, "id" | "fallbackLessons">,
  trackId: TrackId,
  localDate: string,
  variantId?: string | null
): Lesson {
  if (trackId === "general") return fallbackLessonFor(pack.fallbackLessons, localDate);
  if (pack.id === "es" && variantId === "latam") {
    return SPANISH_LATAM_TRACK_FALLBACKS[trackId] ?? fallbackLessonFor(pack.fallbackLessons, localDate);
  }
  return FALLBACKS_BY_LANGUAGE[pack.id][trackId] ?? fallbackLessonFor(pack.fallbackLessons, localDate);
}
